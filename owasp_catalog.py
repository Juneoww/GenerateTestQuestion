def framework_config(framework: str = LLM_FRAMEWORK) -> dict:
    """拒绝未知框架，避免越界编号被静默分配到另一题集。"""
    if type(framework) is not str or framework not in FRAMEWORKS:
        raise ValueError("未知的 OWASP 题集框架。")
    return FRAMEWORKS[framework]


def catalog_for(framework: str = LLM_FRAMEWORK) -> tuple[dict, ...]:
    """返回指定年份和框架的稳定目录顺序。"""
    return framework_config(framework)["risks"]
